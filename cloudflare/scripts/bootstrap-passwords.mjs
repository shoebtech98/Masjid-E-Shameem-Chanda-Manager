/*
 * One-time password re-hash for the D1 migration (controlled workflow).
 *
 * WHY: existing users in the reference DB have scrypt hashes, and scrypt is
 * not available on Workers. After the real-data dump is imported into D1,
 * each user's password must be re-set with PBKDF2-SHA256 in the same format
 * the Cloudflare build verifies (pbkdf2$iter$salt$hash).
 *
 * The script:
 *   - reads users from a LOCAL SQLite file (the reference DB — read-only)
 *   - prompts, one user at a time, for a new password (hidden input)
 *   - computes the PBKDF2 hash locally (Node crypto — identical output to
 *     WebCrypto deriveBits for the same parameters)
 *   - writes UPDATE statements to an SQL file you apply with
 *     `wrangler d1 execute <db> --file <out>.sql`
 *
 * Safety: passwords are never printed, never written to disk, and never
 * appear in shell history (they are read from the prompt, not argv).
 *
 * Usage:
 *   node scripts/bootstrap-passwords.mjs --db ../data/chanda.db --out migrate-passwords.sql
 *   wrangler d1 execute masjid-shameem --file migrate-passwords.sql   # then DELETE the file
 */
import { DatabaseSync } from 'node:sqlite';
import { pbkdf2Sync, randomBytes } from 'node:crypto';
import { writeFileSync, readFileSync } from 'node:fs';
import { createInterface } from 'node:readline/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_DB = path.join(__dirname, '..', '..', 'data', 'chanda.db');

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--db') out.db = argv[++i];
    else if (argv[i] === '--out') out.out = argv[++i];
    else if (argv[i] === '--iterations') out.iterations = Number(argv[++i]);
  }
  return out;
}

const hex = (buf) => buf.toString('hex');

function hashPassword(password, iterations) {
  const salt = randomBytes(16).toString('hex');
  const hash = pbkdf2Sync(password, salt, iterations, 32, 'sha256').toString('hex');
  return `pbkdf2$${iterations}$${salt}$${hash}`;
}

/** Hidden-input prompt (mutes the terminal while typing). */
async function promptHidden(rl, question) {
  return new Promise((resolve) => {
    const orig = rl._writeToOutput?.bind(rl);
    const mute = () => { if (orig) rl._writeToOutput = () => {}; };
    const unmute = () => { if (orig) rl._writeToOutput = orig; };
    mute();
    rl.question(question, (answer) => {
      unmute();
      process.stdout.write('\n');
      resolve(answer);
    });
  });
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const dbPath = args.db ? path.resolve(args.db) : DEFAULT_DB;
  const outPath = args.out ? path.resolve(args.out) : path.join(__dirname, '..', 'migrate-passwords.sql');
  const iterations = Number.isInteger(args.iterations) && args.iterations >= 3000 ? args.iterations : 7000;

  let db;
  try {
    db = new DatabaseSync(dbPath, { readOnly: true });
  } catch (err) {
    console.error(`✗ Cannot open ${dbPath}: ${err.message}`);
    process.exit(1);
  }
  const users = db.prepare('SELECT id, name, email, password_hash FROM users ORDER BY id').all();
  db.close();

  if (!users.length) {
    console.log('No users found — nothing to do.');
    return;
  }

  console.log(`Re-hashing passwords for ${users.length} user(s) with PBKDF2-SHA256 (${iterations} iterations).`);
  console.log('Enter a NEW strong password for each account (min 8 characters). Nothing is echoed or stored.');
  const rl = createInterface({ input: process.stdin, output: process.stdout });

  const updates = [];
  for (const u of users) {
    const current = u.password_hash?.startsWith('pbkdf2$') ? 'already PBKDF2' : 'scrypt (needs re-hash)';
    let password = '';
    while (password.length < 8) {
      password = String(await promptHidden(rl, `New password for ${u.email} (${current}): `)).trim();
      if (password.length < 8) console.log('  Too short — at least 8 characters.');
    }
    updates.push(`UPDATE users SET password_hash = '${hashPassword(password, iterations).replace(/'/g, "''")}' WHERE id = ${u.id};`);
  }
  rl.close();

  if (readFileSync(outPath, 'utf8').length === 0 || !existsSync(outPath)) {
    // never overwrite
  }
  try {
    readFileSync(outPath);
    console.error(`✗ ${outPath} already exists — refusing to overwrite. Choose a different --out or delete it first.`);
    process.exit(1);
  } catch { /* OK — new file */ }

  writeFileSync(outPath, `-- Generated by bootstrap-passwords.mjs — apply then DELETE this file.\n-- Contains ONLY password hashes (no plaintext).\nPRAGMA foreign_keys = OFF;\n${updates.join('\n')}\nPRAGMA foreign_keys = ON;\n`);
  console.log(`\n✓ Wrote ${updates.length} UPDATE statement(s) to ${outPath}`);
  console.log('Apply with:  wrangler d1 execute <db> --file <that file>');
  console.log('Then DELETE the file and verify each user can log in.');
}

function existsSync(p) {
  try { readFileSync(p); return true; } catch { return false; }
}

main().catch((err) => { console.error(err); process.exit(1); });
